// Returns verified animated/illustrated crop graphic
export const getCropPhoto = (cropName: string): string => {
  if (!cropName) return ANIMATED_CROP_IMAGES.default;
  const clean = cropName.toLowerCase().trim();

  // Exact match in animated dictionary
  if (ANIMATED_CROP_IMAGES[clean]) return ANIMATED_CROP_IMAGES[clean];

  // Key substring lookup
  for (const [key, url] of Object.entries(ANIMATED_CROP_IMAGES)) {
    if (key !== 'default' && clean.includes(key)) {
      return url;
    }
  }

  return ANIMATED_CROP_IMAGES.default;
};
